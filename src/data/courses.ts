// Helper to calculate total lessons count
export const TOTAL_LESSONS = COURSES.reduce((acc, course) => acc + course.lessons.length, 0);

// Helper to find a lesson by ID
export function findLessonById(lessonId: string): { course: CourseModule; lesson: import('../types').Lesson; indexInCourse: number } | null {
  for (const course of COURSES) {
    const idx = course.lessons.findIndex(l => l.id === lessonId);
    if (idx !== -1) {
      return { course, lesson: course.lessons[idx], indexInCourse: idx };
    }
  }
  return null;
}

// Helper to get the next lesson in line
export function getNextLessonId(currentLessonId: string): string | null {
  let foundCurrent = false;
  for (const course of COURSES) {
    for (const lesson of course.lessons) {
      if (foundCurrent) {
        return lesson.id;
      }
      if (lesson.id === currentLessonId) {
        foundCurrent = true;
      }
    }
  }
  return null;
}
